describe('calculateMonthly (quote-utils)', () => {
  it('keeps every pinned non-zero payment, total, and interest', () => {
    for (const [amount, rate, termMonths, payment, totalAmount, totalInterest] of PINNED_NONZERO) {
      expect(calculateMonthly(amount, rate, termMonths)).toEqual({
        amount: payment,
        rate,
        termMonths,
        totalAmount,
        totalInterest,
      });
    }
  });

  it('matches finance.calculateMonthlyPayment on rounded payment for non-zero rates', () => {
    for (const [amount, rate, termMonths, payment] of PINNED_NONZERO) {
      expect(calculateMonthlyPayment(amount, rate, termMonths).payment).toBe(payment);
    }
  });

  it('at 0% returns amount / termMonths rounded and zero interest', () => {
    const cases: Array<[number, number]> = [
      [3000, 24],
      [10000, 36],
      [20112.7, 60],
      [40000, 48],
    ];

    for (const [amount, termMonths] of cases) {
      const result = calculateMonthly(amount, 0, termMonths);
      expect(result.amount).toBe(Math.round(amount / termMonths));
      expect(result.totalInterest).toBe(0);
      expect(result.rate).toBe(0);
      expect(Number.isFinite(result.amount)).toBe(true);
    }
  });

  it('quotes $335/mo and $0 interest on $20,112.70 at 0% for 60 months', () => {
    const result = calculateMonthly(20112.7, 0, 60);
    expect(result.amount).toBe(335);
    expect(result.totalInterest).toBe(0);
  });
});
